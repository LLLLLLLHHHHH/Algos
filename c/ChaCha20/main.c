static void phex(const uint8_t *buf, size_t len) {
    for (size_t i = 0; i < len; i++) printf("%02x", buf[i]);
    printf("\n");
}

static void test_hchacha20() {
    // draft-arciszewski-xchacha-03, Section 2.2.1
    uint8_t key[32];
    for (int i = 0; i < 32; i++) key[i] = (uint8_t)i;
    uint8_t nonce16[16] = {
        0x00, 0x00, 0x00, 0x09, 0x00, 0x00, 0x00, 0x4a,
        0x00, 0x00, 0x00, 0x00, 0x31, 0x41, 0x59, 0x27
    };
    uint8_t expected[32] = {
        0x82, 0x41, 0x3b, 0x42, 0x27, 0xb2, 0x7b, 0xfe,
        0xd3, 0x0e, 0x42, 0x50, 0x8a, 0x87, 0x7d, 0x73,
        0xa0, 0xf9, 0xe4, 0xd5, 0x8a, 0x74, 0xa8, 0x53,
        0xc1, 0x2e, 0xc4, 0x13, 0x26, 0xd3, 0xec, 0xdc
    };
    uint8_t out[32];
    hchacha20(key, nonce16, out);
    printf("\nHChaCha20 subkey: "); phex(out, 32);
    printf("HChaCha20 expected: "); phex(expected, 32);
    printf("%s\n", memcmp(out, expected, 32) == 0 ? "HChaCha20 PASS" : "HChaCha20 FAIL");
}

