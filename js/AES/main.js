
const AES = require('./AES');

function phex(str) {
    let output = "";
    for (let i = 0; i < str.length; ++i) {
        let hex = str[i].toString(16);
        if (hex.length < 2) hex = "0" + hex;
        output += hex;
    }
    console.log(output);
}

